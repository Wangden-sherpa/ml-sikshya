<div class="box analogy"><b class="t">直觉：开奶茶店</b>你想在城里开 3 家奶茶店，让每户人家都离某一家店很近。先随便放 3 家店 → 每户去最近的店 → 把每家店搬到它顾客们的中心 → 重复。最后店会停在 3 个社区的中心。这些中心就是<b>质心</b>。</div>
